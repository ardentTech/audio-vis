fn cubic_ease_in(a: f32) -> f32 {
    a * a * a
}

fn quad_ease_in_out(a: f32) -> f32 {
    if a < 0.5 {
        2f32 * a * a
    } else {
        1f32 - (-2f32 * a + 2f32) * (-2f32 * a + 2f32) / 2f32
    }
}

fn quint_ease_in(a: f32) -> f32 {
    a * a * a * a * a
}

